// Builds the GNOME Shell extension from gnome-extension/src/core.js:
//   extension.js         GNOME 45+ (ES modules)
//   legacy/extension.js  GNOME 42–44 (imports.*), with its own metadata.json
//   node scripts/build-gnome-extension.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../gnome-extension/', import.meta.url);
const uuid = 'charger-cat@jaisudhakar.github.io';
const core = (await readFile(new URL('src/core.js', root), 'utf8')).trimEnd();
const banner = '// Generated by scripts/build-gnome-extension.mjs from gnome-extension/src/core.js.\n';

const modern = `${banner}import GLib from 'gi://GLib';
import Gio from 'gi://Gio';
import St from 'gi://St';
import Clutter from 'gi://Clutter';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';
import {Extension} from 'resource:///org/gnome/shell/extensions/extension.js';

${core}

export default class ChargerCatExtension extends Extension {
    enable() {
        this._cat = new ChargerCat(this.path);
    }

    disable() {
        this._cat?.destroy();
        this._cat = null;
    }

    // Used by tests.
    get cat() {
        return this._cat;
    }
}
`;

const legacy = `${banner}const {GLib, Gio, St, Clutter} = imports.gi;
const Main = imports.ui.main;
const ExtensionUtils = imports.misc.extensionUtils;

${core}

class ChargerCatExtension {
    enable() {
        this._cat = new ChargerCat(ExtensionUtils.getCurrentExtension().path);
    }

    disable() {
        this._cat?.destroy();
        this._cat = null;
    }
}

function init() {
    return new ChargerCatExtension();
}
`;

const metadata = (versions) => JSON.stringify({
  uuid,
  name: 'Charger Cat',
  description: 'A 3D cat runs next to the battery icon in the top bar while your charger is plugged in, and sits purring when the battery is full.',
  'shell-version': versions,
  url: 'https://github.com/jaisudhakar/charger-pet',
  version: 1,
}, null, 2) + '\n';

const ext = new URL(`${uuid}/`, root);
await writeFile(new URL('extension.js', ext), modern);
await writeFile(new URL('metadata.json', ext), metadata(['45', '46', '47', '48', '49']));
await mkdir(new URL('legacy/', root), { recursive: true });
await writeFile(new URL('legacy/extension.js', root), legacy);
await writeFile(new URL('legacy/metadata.json', root), metadata(['42', '43', '44']));
console.log('Built', uuid);
