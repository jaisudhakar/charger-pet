// Builds the GNOME Shell extension from shared/brain.js + gnome/src/core.js:
//   gnome/cursor-cat@jaisudhakar.github.io/extension.js   GNOME 45+ (ES modules)
//   gnome/legacy/extension.js                             GNOME 42–44 (imports.*)
// The installer copies the sprites in. Run with: npm run build:gnome
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const repo = new URL('../', import.meta.url);
const uuid = 'cursor-cat@jaisudhakar.github.io';
const brain = (await readFile(new URL('shared/brain.js', repo), 'utf8'))
  .replace(/^export /gm, '')
  .trimEnd();
const core = (await readFile(new URL('gnome/src/core.js', repo), 'utf8')).trimEnd();
const banner = '// Generated by scripts/build-gnome.mjs from shared/brain.js and gnome/src/core.js.\n';

const modern = `${banner}import GLib from 'gi://GLib';
import Gio from 'gi://Gio';
import St from 'gi://St';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';
import {Extension} from 'resource:///org/gnome/shell/extensions/extension.js';

${brain}

${core}

export default class CursorCatExtension extends Extension {
    enable() {
        this._cat = new CursorCat(this.path);
    }

    disable() {
        this._cat?.destroy();
        this._cat = null;
    }

    // Used by tests.
    get cat() {
        return this._cat;
    }
}
`;

const legacy = `${banner}const {GLib, Gio, St} = imports.gi;
const Main = imports.ui.main;
const ExtensionUtils = imports.misc.extensionUtils;

${brain}

${core}

class CursorCatExtension {
    enable() {
        this._cat = new CursorCat(ExtensionUtils.getCurrentExtension().path);
    }

    disable() {
        this._cat?.destroy();
        this._cat = null;
    }
}

function init() {
    return new CursorCatExtension();
}
`;

const metadata = (versions) => `${JSON.stringify({
  uuid,
  name: 'Cursor Cat',
  description: 'A 3D cat that chases your mouse pointer around the screen. When it catches up it sits, grooms, yawns and naps.',
  'shell-version': versions,
  url: 'https://github.com/jaisudhakar/charger-pet',
  version: 1,
}, null, 2)}\n`;

const ext = new URL(`gnome/${uuid}/`, repo);
await mkdir(ext, { recursive: true });
await writeFile(new URL('extension.js', ext), modern);
await writeFile(new URL('metadata.json', ext), metadata(['45', '46', '47', '48', '49']));
await mkdir(new URL('gnome/legacy/', repo), { recursive: true });
await writeFile(new URL('gnome/legacy/extension.js', repo), legacy);
await writeFile(new URL('gnome/legacy/metadata.json', repo), metadata(['42', '43', '44']));
console.log('Built', uuid);
